  fun filter(query: String, category: String): List<CssPart> {
    val needle = query.trim().lowercase()
    return parts.filter { part ->
      val catOk = category == ALL || part.category == category
      if (!catOk) return@filter false
      if (needle.isEmpty()) return@filter true
      part.title.lowercase().contains(needle) ||
        part.summary.lowercase().contains(needle) ||
        part.category.lowercase().contains(needle) ||
        part.overview.lowercase().contains(needle) ||
        part.cssUse.lowercase().contains(needle)
    }
  }
